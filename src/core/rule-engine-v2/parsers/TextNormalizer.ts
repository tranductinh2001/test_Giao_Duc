/**
 * Text Normalizer
 *
 * Normalize text for better matching
 */

export interface NormalizationOptions {
  lowercase?: boolean;
  removeAccents?: boolean;
  normalizeSpaces?: boolean;
  removeSpecialChars?: boolean;
  removePunctuation?: boolean;
}

export class TextNormalizer {
  /**
   * Normalize text based on options
   */
  static normalize(text: string, options: NormalizationOptions = {}): string {
    let result = text;

    if (options.lowercase) {
      result = result.toLowerCase();
    }

    if (options.removeAccents) {
      result = this.removeAccents(result);
    }

    if (options.normalizeSpaces) {
      result = result.replace(/\s+/g, ' ').trim();
    }

    if (options.removeSpecialChars) {
      result = result.replace(/[^\w\s]/g, '');
    }

    if (options.removePunctuation) {
      result = result.replace(/[.,;:!?()[\]{}'"]/g, '');
    }

    return result;
  }

  /**
   * Remove Vietnamese accents
   */
  static removeAccents(text: string): string {
    const accents: Record<string, string> = {
      'à': 'a', 'á': 'a', 'ạ': 'a', 'ả': 'a', 'ã': 'a',
      'â': 'a', 'ầ': 'a', 'ấ': 'a', 'ậ': 'a', 'ẩ': 'a', 'ẫ': 'a',
      'ă': 'a', 'ằ': 'a', 'ắ': 'a', 'ặ': 'a', 'ẳ': 'a', 'ẵ': 'a',
      'è': 'e', 'é': 'e', 'ẹ': 'e', 'ẻ': 'e', 'ẽ': 'e',
      'ê': 'e', 'ề': 'e', 'ế': 'e', 'ệ': 'e', 'ể': 'e', 'ễ': 'e',
      'ì': 'i', 'í': 'i', 'ị': 'i', 'ỉ': 'i', 'ĩ': 'i',
      'ò': 'o', 'ó': 'o', 'ọ': 'o', 'ỏ': 'o', 'õ': 'o',
      'ô': 'o', 'ồ': 'o', 'ố': 'o', 'ộ': 'o', 'ổ': 'o', 'ỗ': 'o',
      'ơ': 'o', 'ờ': 'o', 'ớ': 'o', 'ợ': 'o', 'ở': 'o', 'ỡ': 'o',
      'ù': 'u', 'ú': 'u', 'ụ': 'u', 'ủ': 'u', 'ũ': 'u',
      'ư': 'u', 'ừ': 'u', 'ứ': 'u', 'ự': 'u', 'ử': 'u', 'ữ': 'u',
      'ỳ': 'y', 'ý': 'y', 'ỵ': 'y', 'ỷ': 'y', 'ỹ': 'y',
      'đ': 'd',
      'À': 'A', 'Á': 'A', 'Ạ': 'A', 'Ả': 'A', 'Ã': 'A',
      'Â': 'A', 'Ầ': 'A', 'Ấ': 'A', 'Ậ': 'A', 'Ẩ': 'A', 'Ẫ': 'A',
      'Ă': 'A', 'Ằ': 'A', 'Ắ': 'A', 'Ặ': 'A', 'Ẳ': 'A', 'Ẵ': 'A',
      'È': 'E', 'É': 'E', 'Ẹ': 'E', 'Ẻ': 'E', 'Ẽ': 'E',
      'Ê': 'E', 'Ề': 'E', 'Ế': 'E', 'Ệ': 'E', 'Ể': 'E', 'Ễ': 'E',
      'Ì': 'I', 'Í': 'I', 'Ị': 'I', 'Ỉ': 'I', 'Ĩ': 'I',
      'Ò': 'O', 'Ó': 'O', 'Ọ': 'O', 'Ỏ': 'O', 'Õ': 'O',
      'Ô': 'O', 'Ồ': 'O', 'Ố': 'O', 'Ộ': 'O', 'Ổ': 'O', 'Ỗ': 'O',
      'Ơ': 'O', 'Ờ': 'O', 'Ớ': 'O', 'Ợ': 'O', 'Ở': 'O', 'Ỡ': 'O',
      'Ù': 'U', 'Ú': 'U', 'Ụ': 'U', 'Ủ': 'U', 'Ũ': 'U',
      'Ư': 'U', 'Ừ': 'U', 'Ứ': 'U', 'Ự': 'U', 'Ử': 'U', 'Ữ': 'U',
      'Ỳ': 'Y', 'Ý': 'Y', 'Ỵ': 'Y', 'Ỷ': 'Y', 'Ỹ': 'Y',
      'Đ': 'D',
    };

    return text.replace(/./g, char => accents[char] || char);
  }

  /**
   * Extract numbering prefix from text
   * E.g., "1. Mục tiêu" -> { prefix: "1.", text: "Mục tiêu" }
   */
  static extractNumbering(text: string): { prefix: string; text: string } {
    const patterns = [
      /^(\d+\.)\s*/,           // 1. 2. 3.
      /^([A-Z]\.)\s*/,         // A. B. C.
      /^([IVX]+\.)\s*/,        // I. II. III.
      /^([a-z]\))\s*/,         // a) b) c)
      /^(\d+\))\s*/,           // 1) 2) 3)
      /^([-•*])\s*/,           // - • *
    ];

    for (const pattern of patterns) {
      const match = text.match(pattern);
      if (match) {
        return {
          prefix: match[1],
          text: text.substring(match[0].length).trim(),
        };
      }
    }

    return { prefix: '', text: text.trim() };
  }

  /**
   * Calculate Levenshtein distance for fuzzy matching
   */
  static levenshteinDistance(str1: string, str2: string): number {
    const m = str1.length;
    const n = str2.length;
    const dp: number[][] = Array(m + 1).fill(0).map(() => Array(n + 1).fill(0));

    for (let i = 0; i <= m; i++) dp[i][0] = i;
    for (let j = 0; j <= n; j++) dp[0][j] = j;

    for (let i = 1; i <= m; i++) {
      for (let j = 1; j <= n; j++) {
        if (str1[i - 1] === str2[j - 1]) {
          dp[i][j] = dp[i - 1][j - 1];
        } else {
          dp[i][j] = Math.min(
            dp[i - 1][j] + 1,      // deletion
            dp[i][j - 1] + 1,      // insertion
            dp[i - 1][j - 1] + 1   // substitution
          );
        }
      }
    }

    return dp[m][n];
  }

  /**
   * Calculate similarity score (0-1)
   */
  static similarity(str1: string, str2: string): number {
    const maxLen = Math.max(str1.length, str2.length);
    if (maxLen === 0) return 1.0;

    const distance = this.levenshteinDistance(str1, str2);
    return 1 - distance / maxLen;
  }
}
